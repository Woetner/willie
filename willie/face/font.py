def normalise(text):
    text = str(text).replace("µ", "U").replace("Ω", " OHM").replace("×", "X")
    text = text.replace("–", "-").replace("—", "-").replace("’", "'").replace("…", "...")
    return "".join(c for c in unicodedata.normalize("NFKD", text).upper()
                   if not unicodedata.combining(c))


def lines(text, columns):
    result = []
    for paragraph in normalise(text).splitlines():
        result.extend(textwrap.wrap(paragraph, width=max(1, columns),
                                    replace_whitespace=True) or [""])
    return result or [""]


def draw(surface, text, x, y, scale, colour):
    for char in normalise(text):
        for row, bits in enumerate(FONT.get(char, FONT["?"])):
            for col, bit in enumerate(bits):
                if bit == "1":
                    surface.rect(x + col * scale, y + row * scale, scale, scale, colour)
        x += 6 * scale
